#!/usr/bin/env node
/**
 * Generates apps/client/src/renderer/emoji/emojiCatalog.ts from the official
 * Unicode data files (#356).
 *
 * We ship the catalog as source instead of pulling an emoji npm package so the
 * app has no extra runtime dependency and the picker works fully offline.
 *
 * Sources (both under the permissive Unicode-3.0 licence):
 *   - emoji-test.txt   -> the emoji themselves, their official group and English name
 *   - CLDR annotations -> Portuguese name + search keywords
 *
 * Usage:
 *   node scripts/generate-emoji-catalog.cjs <emoji-test.txt> <pt.xml> <pt_derived.xml>
 */

const fs = require('fs');
const path = require('path');

const [testFile, ptFile, ptDerivedFile] = process.argv.slice(2);
if (!testFile || !ptFile || !ptDerivedFile) {
  console.error('usage: node scripts/generate-emoji-catalog.cjs <emoji-test.txt> <pt.xml> <pt_derived.xml>');
  process.exit(1);
}

/** Unicode group name -> our internal id. Groups not listed here are dropped. */
const GROUPS = {
  'Smileys & Emotion': 'smileys',
  'People & Body': 'people',
  'Animals & Nature': 'nature',
  'Food & Drink': 'food',
  'Travel & Places': 'travel',
  Activities: 'activities',
  Objects: 'objects',
  Symbols: 'symbols',
  Flags: 'flags',
};

const SKIN_TONES = /[\u{1F3FB}-\u{1F3FF}]/u;
const VARIATION_SELECTOR = /\uFE0F/g;

/** Parses the `<annotation>` entries of a CLDR annotations file into a map. */
function parseAnnotations(file, names, keywords) {
  const xml = fs.readFileSync(file, 'utf8');
  const re = /<annotation cp="([^"]*)"(?:\s+type="(tts)")?\s*>([^<]*)<\/annotation>/g;
  let m;
  while ((m = re.exec(xml)) !== null) {
    const cp = decodeEntities(m[1]);
    const value = decodeEntities(m[3]).trim();
    if (!value) continue;
    if (m[2] === 'tts') {
      if (!names.has(cp)) names.set(cp, value);
    } else if (!keywords.has(cp)) {
      keywords.set(cp, value.split('|').map((k) => k.trim()).filter(Boolean));
    }
  }
}

function decodeEntities(raw) {
  return raw
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number(dec)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');
}

/** Strips accents so "coração" also matches a query typed as "coracao". */
function fold(text) {
  return text.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
}

const ptNames = new Map();
const ptKeywords = new Map();
parseAnnotations(ptFile, ptNames, ptKeywords);
parseAnnotations(ptDerivedFile, ptNames, ptKeywords);

const groups = new Map(Object.values(GROUPS).map((id) => [id, []]));
let currentGroup = null;
let skipped = 0;

for (const line of fs.readFileSync(testFile, 'utf8').split(/\r?\n/)) {
  const groupHeader = line.match(/^#\s*group:\s*(.+?)\s*$/);
  if (groupHeader) {
    currentGroup = GROUPS[groupHeader[1]] ?? null;
    continue;
  }
  if (!currentGroup || line.startsWith('#') || !line.trim()) continue;

  // e.g. `1F600 ; fully-qualified # 😀 E1.0 grinning face`
  const entry = line.match(/^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E\d+\.\d+\s+(.+?)\s*$/);
  if (!entry) continue;

  const [, char, englishName] = entry;
  // Skin-tone variants would multiply the catalog fivefold for the same picture;
  // the picker shows the neutral form only.
  if (SKIN_TONES.test(char)) {
    skipped++;
    continue;
  }

  // CLDR strips U+FE0F from its `cp` keys, so look the emoji up without it.
  const key = char.replace(VARIATION_SELECTOR, '');
  const terms = new Set([fold(englishName)]);
  const ptName = ptNames.get(key);
  if (ptName) terms.add(fold(ptName));
  for (const keyword of ptKeywords.get(key) ?? []) terms.add(fold(keyword));

  groups.get(currentGroup).push([char, ptName || englishName, [...terms].join(' ')]);
}

const total = [...groups.values()].reduce((sum, list) => sum + list.length, 0);

const body = [...groups.entries()]
  .map(([id, list]) => {
    const entries = list.map(([c, n, k]) => `    [${JSON.stringify(c)}, ${JSON.stringify(n)}, ${JSON.stringify(k)}],`);
    return `  {\n    id: '${id}',\n    emojis: [\n${entries.join('\n')}\n    ],\n  },`;
  })
  .join('\n');

const out = `// AUTO-GENERATED by scripts/generate-emoji-catalog.cjs — do not edit by hand.
// Source: Unicode emoji-test.txt + CLDR pt annotations (Unicode-3.0 licence).
// Skin-tone variants are intentionally omitted: they are the same picture and
// would multiply the catalog fivefold.

/** \`[character, pt-BR name, space-separated accent-folded search terms]\` */
export type EmojiEntry = readonly [char: string, name: string, terms: string];

export type EmojiGroupId =
${[...groups.keys()].map((id) => `  | '${id}'`).join('\n')};

export interface EmojiGroup {
  readonly id: EmojiGroupId;
  readonly emojis: readonly EmojiEntry[];
}

export const EMOJI_CATALOG: readonly EmojiGroup[] = [
${body}
];
`;

const target = path.join(__dirname, '..', 'apps', 'client', 'src', 'renderer', 'emoji', 'emojiCatalog.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out, 'utf8');
console.log(`wrote ${total} emojis (${skipped} skin-tone variants skipped) to ${target}`);
